import { seededRng as mulberry32 } from '../cards.js';

// One shared drill per calendar day: five hands, same seed string for everyone
// who opens the game on the same local date. Nothing here talks to a server.

export const DAILY_HANDS = 5;
export const DAILY_GAMES = ['videopoker', 'blackjack', 'baccarat', 'holdem'];
export const DAILY_LAUNCH_KEY = '2026-01-01';

const DAY_MS = 86400000;

// 'YYYY-MM-DD' in the player's own time zone, so the drill flips at local midnight.
export function dailyKey(date = new Date()) {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

export function keyToDay(key) {
  const [y, m, d] = String(key).split('-').map(Number);
  return Math.floor(Date.UTC(y, m - 1, d) / DAY_MS);
}

export function dayGap(aKey, bKey) {
  return keyToDay(aKey) - keyToDay(bKey);
}

// FNV-1a over the seed string, then mulberry32. Pure: same string, same stream.
export function hashSeed(seedString) {
  let h = 2166136261 >>> 0;
  const text = String(seedString);
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function seededRng(seedString) {
  return mulberry32(hashSeed(seedString));
}

// Day count since the fixed launch date, so the card can say "Daily #42".
export function dailyNumber(key) {
  return Math.max(1, keyToDay(key) - keyToDay(DAILY_LAUNCH_KEY) + 1);
}

// Five hand descriptors. A Fisher-Yates shuffle of all four games, then one
// game repeated and the whole list reshuffled, so every drill includes each of
// the four games at least once and the duplicate is not always in last place.
// Preserve this algorithm for old history entries without captured game IDs.
export function dailyPlanV1(key) {
  const rng = seededRng(`plan:${key}`);
  const games = DAILY_GAMES.slice();
  for (let i = games.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [games[i], games[j]] = [games[j], games[i]];
  }
  const repeat = Math.floor(rng() * DAILY_GAMES.length) % DAILY_GAMES.length;
  games.push(games[repeat]);
  for (let i = games.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [games[i], games[j]] = [games[j], games[i]];
  }
  return games.map((game, i) => ({ game, seed: `${key}#${i}` }));
}

export function dailyPlan(key) {
  return dailyPlanV1(key);
}

export function validDailyGames(games) {
  return Array.isArray(games) && games.length === DAILY_HANDS &&
    games.every(game => DAILY_GAMES.includes(game));
}

export function validDailyPlan(plan) {
  return Array.isArray(plan) && plan.length === DAILY_HANDS && plan.every(hand =>
    hand && DAILY_GAMES.includes(hand.game) && typeof hand.seed === 'string' &&
    hand.seed.length > 0 && hand.seed.length <= 100);
}

// Legacy unfinished drills were generated by V1. Keep their remaining hands
// stable even when the algorithm for new drills eventually changes.
export function dailySession(key, progress) {
  const resumable = progress?.key === key && Number.isInteger(progress.index) &&
    progress.index >= 0 && progress.index < DAILY_HANDS &&
    Array.isArray(progress.results) && progress.results.length === progress.index &&
    progress.results.every(value => typeof value === 'boolean') &&
    (progress.plan === undefined || validDailyPlan(progress.plan));
  const plan = resumable ? (progress.plan ?? dailyPlanV1(key)) : dailyPlan(key);
  return { plan: plan.map(hand => ({ game: hand.game, seed: hand.seed })),
    index: resumable ? progress.index : 0,
    results: resumable ? [...progress.results] : [] };
}

export const DAILY_GAME_LABEL = {
  videopoker: 'video poker',
  blackjack: 'blackjack',
  baccarat: 'baccarat',
  holdem: "hold'em",
};

// Time remaining until local midnight, when the next Daily Drill unlocks.
export function formatDailyCountdown(now = new Date()) {
  const nextMidnight = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1);
  const diffMs = Math.max(60000, nextMidnight.getTime() - now.getTime());
  const totalMinutes = Math.ceil(diffMs / 60000);
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;
  if (hours <= 0) return `${minutes}M`;
  return minutes > 0 ? `${hours}H ${minutes}M` : `${hours}H`;
}

// Calendar windows, not the last seven sessions: a missed day is no attempt.
// Only complete first-attempt records count. Replays never replace them.
export function dailySummary(history = [], today = dailyKey()) {
  const seen = new Set();
  const entries = (Array.isArray(history) ? history : []).filter(entry => {
    if (!entry || !/^\d{4}-\d{2}-\d{2}$/.test(entry.key) || seen.has(entry.key) ||
        !Array.isArray(entry.results) || entry.results.length !== DAILY_HANDS ||
        !entry.results.every(value => typeof value === 'boolean') ||
        (entry.games !== undefined && !validDailyGames(entry.games))) return false;
    const gap = dayGap(today, entry.key);
    if (!Number.isFinite(gap) || gap < 0 || gap >= 14) return false;
    if (new Date(keyToDay(entry.key) * DAY_MS).toISOString().slice(0, 10) !== entry.key) return false;
    seen.add(entry.key);
    return true;
  }).sort((a, b) => b.key.localeCompare(a.key));
  const tally = rows => ({ sessions: rows.length, hands: rows.length * DAILY_HANDS,
    correct: rows.reduce((sum, row) => sum + row.results.filter(Boolean).length, 0) });
  const recent = entries.filter(entry => dayGap(today, entry.key) < 7);
  const previous = entries.filter(entry => dayGap(today, entry.key) >= 7);
  const games = DAILY_GAMES.map(game => ({ game, correct: 0, hands: 0 }));
  for (const entry of recent) {
    const playedGames = entry.games ?? dailyPlanV1(entry.key).map(hand => hand.game);
    playedGames.forEach((gameId, i) => {
      const game = games.find(row => row.game === gameId);
      game.hands++;
      if (entry.results[i]) game.correct++;
    });
  }
  return { recent: tally(recent), previous: tally(previous), games,
    entries: entries.map(entry => ({ key: entry.key, correct: entry.results.filter(Boolean).length })) };
}
